#!/usr/bin/env node
// Bundles the MCP server into a single dependency-free file so the plugin works
// straight from a git checkout (Cursor does not run `npm install` for plugins).
import { build } from "esbuild";
import { chmodSync, readFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const outfile = "dist/ig-broker-mcp.mjs";

await build({
  entryPoints: ["server/src/index.ts"],
  outfile,
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  minify: false,
  sourcemap: false,
  legalComments: "eof",
  banner: {
    js: [
      "#!/usr/bin/env node",
      `// IG Broker MCP server v${pkg.version} - generated by scripts/build.mjs from server/src. Do not edit.`,
      "import { createRequire as __igCreateRequire } from 'node:module'; const require = __igCreateRequire(import.meta.url);",
    ].join("\n"),
  },
  logLevel: "info",
});

chmodSync(outfile, 0o755);
